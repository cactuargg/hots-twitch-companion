func Text(lang, key string, args ...any) string {
	table := messages[Normalize(lang)]
	s, ok := table[key]
	if !ok {
		if s, ok = messages[En][key]; !ok {
			return key
		}
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}
